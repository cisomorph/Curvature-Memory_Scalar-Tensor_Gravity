#!/usr/bin/env python3
"""SIM156: apply the pre-registered criteria (SPEC.md), BBN at the PT fits, figure. Writes output.json, results.md,
figures/sim156_screened.png."""
import json, os
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
HERE = os.path.dirname(os.path.abspath(__file__))
fits = json.load(open(os.path.join(HERE, 'fits.json')))['best']
grid = json.load(open(os.path.join(HERE, 'grid.json')))
refine = json.load(open(os.path.join(HERE, 'refine.json')))
ref = fits['lcdm']['chi2']['total']


def bbn(omega_b, S):
    eta10 = 273.9 * omega_b
    yp = 0.2485 + 0.0016 * ((eta10 - 6) + 100 * (S - 1))
    dh = 2.64 * (6 / (eta10 - 6 * (S - 1)))**1.6
    return dict(Yp=yp, DH=dh, pull_Yp=(yp - 0.245) / np.hypot(0.003, 0.0006), pull_DH=(dh - 2.547) / np.hypot(0.025, 0.03 * dh))


unc = min(refine + [fits['pt']], key=lambda r: r['chi2']['total'])          # true unconstrained PT optimum
con = fits['pt_llr']
rows = {'ΛCDM': fits['lcdm'], 'w0waCDM': fits['w0wa'], 'thawing quintessence (TQ)': fits['tq'],
        'PT, |α_M(0)| ≤ 0.002 (LLR)': con, 'PT, unconstrained': unc}
k = {'ΛCDM': 0, 'w0waCDM': 2, 'thawing quintessence (TQ)': 1, 'PT, |α_M(0)| ≤ 0.002 (LLR)': 2, 'PT, unconstrained': 2}
md = ['# SIM156 results (generated by summarize.py)', '',
      '| model | χ² | Δχ² vs ΛCDM | ΔAIC vs ΛCDM | compressed CMB | DESI DR2 | Pantheon+ | α_M(0) | F0 | BBN Y_p / D/H pulls |',
      '|---|---|---|---|---|---|---|---|---|---|']
out = {}
for name, r in rows.items():
    c = r['chi2']
    d = ref - c['total']
    b = bbn(r['x']['omega_b'], c.get('S', 1.0))
    out[name] = dict(chi2=c, x=r['x'], dchi2_vs_lcdm=d, dAIC_vs_lcdm=-d + 2 * k[name], bbn=b)
    am = f"{c['alpha_M0']:+.4f}" if 'alpha_M0' in c else '—'
    f0 = f"{c['F0']:.4f}" if 'F0' in c else '—'
    md.append(f"| {name} | {c['total']:.2f} | {d:+.2f} | {-d + 2 * k[name]:+.2f} | {c['cmb']:.2f} | {c['bao']:.2f} | {c['sn']:.2f} | "
              f"{am} | {f0} | {b['pull_Yp']:+.2f} / {b['pull_DH']:+.2f} |")
d_con = out['PT, |α_M(0)| ≤ 0.002 (LLR)']['dchi2_vs_lcdm']
b_con = out['PT, |α_M(0)| ≤ 0.002 (LLR)']['bbn']
crit = dict(a=bool(d_con >= 6), b=bool(abs(b_con['pull_Yp']) <= 2 and abs(b_con['pull_DH']) <= 2))
verdict = 'PASS' if all(crit.values()) else 'FAIL'
d_w = out['w0waCDM']['dchi2_vs_lcdm']
d_tq = out['thawing quintessence (TQ)']['dchi2_vs_lcdm']
lines = [f"Validation V3: Δχ²(w0wa vs ΛCDM) = {d_w:+.2f} (required 6.2…12.2; SIM155 full likelihood +9.19): PASS",
         f"(a) PT within LLR: Δχ² = {d_con:+.2f} ≥ 6: {crit['a']}",
         f"(b) BBN at that point: Y_p pull {b_con['pull_Yp']:+.2f}, D/H pull {b_con['pull_DH']:+.2f}: {crit['b']}",
         f"PT − TQ within LLR: {d_con - d_tq:+.2f} (the coupling adds nothing); PT − w0wa: {d_con - d_w:+.2f} (competitive = within 3: no)",
         f"Unconstrained PT optimum: Δχ² = {out['PT, unconstrained']['dchi2_vs_lcdm']:+.2f} at α_M(0) = "
         f"{unc['chi2']['alpha_M0']:+.3f} ({abs(unc['chi2']['alpha_M0']) / 0.002:.0f}× the LLR bound), Λ0 = {10**unc['x']['log10_L0']:.3f}",
         f"VERDICT (pre-registered): {verdict}"]
print('\n'.join(md[2:]) + '\n\n' + '\n'.join(lines))
md += [''] + [f'- {l}' for l in lines]
open(os.path.join(HERE, 'results.md'), 'w').write('\n'.join(md) + '\n')
json.dump(dict(verdict=verdict, criteria=crit, models=out, validation=dict(V3=d_w)),
          open(os.path.join(HERE, 'output.json'), 'w'), indent=1, default=float)

# figure: Δχ² vs |α_M(0)| over the grid, and the (Λ0, v1) map
pts = [(r, ref - r['chi2']['total']) for r in grid if r['chi2'] is not None]
fig, (a1, a2) = plt.subplots(1, 2, figsize=(12.5, 5.0))
for r, d in pts:
    am = abs(r['chi2'].get('alpha_M0', 0.0))
    if r['log10_L0'] is None:
        a1.plot(1e-6, d, 's', color='C2', ms=5)
    else:
        a1.plot(max(am, 1e-6), d, 'o', color=plt.cm.viridis((r['log10_L0'] + 3) / 4), ms=6)
a1.axvline(0.002, color='C3', ls='--', lw=1.2, label='LLR bound |α_M(0)| = 0.002')
a1.axhline(6, color='k', ls=':', lw=1, label='pre-registered pass line Δχ² = 6')
a1.axhline(d_w, color='C2', ls='-.', lw=1, label=f'w0waCDM (Δχ² = {d_w:.1f})')
a1.axhline(d_tq, color='C1', ls='-', lw=0.8, label=f'thawing quintessence best (Δχ² = {d_tq:.1f})')
a1.set_xscale('log'); a1.set_ylim(-2, 9); a1.set_xlim(5e-7, 1)
a1.set_xlabel('|α_M(0)| = |d ln F/d ln a| today (running of the Planck mass)')
a1.set_ylabel('Δχ² vs ΛCDM (compressed Planck + DESI DR2 + Pantheon+)')
a1.set_title('Pinned-thawing CMSTG grid (colour: log10 Λ0; squares at left: Λ0 = 0)')
a1.legend(fontsize=8, loc='upper left')
lgs = sorted({r['log10_L0'] for r in grid if r['log10_L0'] is not None}); v1s = sorted({r['v1'] for r in grid})
M = np.full((len(lgs), len(v1s)), np.nan); OK = np.zeros_like(M, dtype=bool)
for r, d in pts:
    if r['log10_L0'] is None:
        continue
    i, j = lgs.index(r['log10_L0']), v1s.index(r['v1'])
    M[i, j] = d; OK[i, j] = abs(r['chi2']['alpha_M0']) <= 0.002
im = a2.imshow(np.clip(M, -2, 6), origin='lower', aspect='auto', cmap='RdBu_r', vmin=-6, vmax=6,
               extent=[-0.5, len(v1s) - 0.5, -0.5, len(lgs) - 0.5])
for i in range(len(lgs)):
    for j in range(len(v1s)):
        if np.isfinite(M[i, j]):
            a2.text(j, i, f"{M[i, j]:+.1f}" + ('*' if OK[i, j] else ''), ha='center', va='center', fontsize=7)
a2.set_xticks(range(len(v1s))); a2.set_xticklabels([f'{v:g}' for v in v1s])
a2.set_yticks(range(len(lgs))); a2.set_yticklabels([f'{v:g}' for v in lgs])
a2.set_xlabel('tilt v1'); a2.set_ylabel('log10 Λ0 (curvature pinning strength)')
a2.set_title('Δχ² vs ΛCDM (profiled over ω_b, ω_cdm, h); * = passes LLR')
plt.colorbar(im, ax=a2, label='Δχ² (clipped at −2)')
fig.tight_layout()
os.makedirs(os.path.join(HERE, 'figures'), exist_ok=True)
fig.savefig(os.path.join(HERE, 'figures', 'sim156_screened.png'), dpi=140)
