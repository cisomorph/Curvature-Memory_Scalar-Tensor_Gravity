#!/usr/bin/env python3
"""SIM157: apply the pre-registered criteria (SPEC.md), write output.json / results.md, figure figures/sim157_dark.png."""
import json, os, sys
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run
import dark as D

fits = json.load(open(os.path.join(HERE, 'fits.json')))['best']
# w_eff diagnostics in fits.json came from a z-ordering bug in dark.w_eff (fixed; criteria unaffected): recompute the
# DPT best-fit χ² dict with the fixed function.
_x = fits['dpt']['x']
fits['dpt']['chi2'] = run.evaluate('dpt', np.array([_x['omega_b'], _x['omega_cdm'], _x['h'], _x['log10_L0'], _x['v1']]))
grid = [r for r in json.load(open(os.path.join(HERE, 'grid.json')))]
ref = fits['lcdm']['chi2']
K = {'lcdm': 0, 'w0wa': 2, 'tq': 1, 'dpt': 2}
names = {'lcdm': 'ΛCDM', 'w0wa': 'w0waCDM', 'tq': 'thawing quintessence (TQ)', 'dpt': 'DPT (dark curvature memory)'}
rows, out = [], {}
for k in ('lcdm', 'w0wa', 'tq', 'dpt'):
    c = fits[k]['chi2']
    d_j, d_b, d_r = ref['total'] - c['total'], ref['background'] - c['background'], ref['rsd'] - c['rsd']
    out[k] = dict(x=fits[k]['x'], chi2=c, dchi2_joint=d_j, dchi2_background=d_b, dchi2_rsd=d_r, dAIC_joint=-d_j + 2 * K[k])
    rows.append(f"| {names[k]} | {c['total']:.2f} | {d_j:+.2f} | {d_b:+.2f} | {d_r:+.2f} | {-d_j + 2 * K[k]:+.2f} | {c['S8']:.4f} | "
                + (f"{c['A0'] - 1:+.4f}" if 'A0' in c else '—') + ' |')
c = fits['dpt']['chi2']
crit = dict(a=bool(out['dpt']['dchi2_background'] >= 6), b=bool(-out['dpt']['dchi2_rsd'] <= 4), c=bool(c['beta_hi'] < 1e-3))
verdict = 'PASS' if all(crit.values()) else 'FAIL'
lines = [f"(a) Δχ²_background vs ΛCDM = {out['dpt']['dchi2_background']:+.2f} ≥ 6: {crit['a']}",
         f"(b) growth: χ²_RSD(DPT) − χ²_RSD(ΛCDM) = {-out['dpt']['dchi2_rsd']:+.2f} ≤ 4: {crit['b']}",
         f"(c) coupling before recombination |β(z ≥ 1000)| = {c['beta_hi']:.1e} < 1e-3: {crit['c']}",
         f"DPT − TQ: background {out['dpt']['dchi2_background'] - out['tq']['dchi2_background']:+.2f}, joint "
         f"{out['dpt']['dchi2_joint'] - out['tq']['dchi2_joint']:+.2f}; DPT − w0wa (background): "
         f"{out['dpt']['dchi2_background'] - out['w0wa']['dchi2_background']:+.2f} (competitive = within 3: "
         f"{abs(out['dpt']['dchi2_background'] - out['w0wa']['dchi2_background']) <= 3})",
         f"DPT best fit: Λ0 = {10 ** fits['dpt']['x']['log10_L0']:.3g}, v1 = {fits['dpt']['x']['v1']:.3f}; dark matter "
         f"{100 * (c['A0'] - 1):+.2f}% heavier today; S8 = {c['S8']:.4f} (ΛCDM {ref['S8']:.4f}); "
         f"w_eff(z = 0, 0.5, 1) = {c['w_eff']['0.0']:.3f}, {c['w_eff']['0.5']:.3f}, {c['w_eff']['1.0']:.3f}; "
         f"crosses −1: {c['crosses']}",
         f"VERDICT (pre-registered): {verdict}"]
md = ['# SIM157 results (generated by summarize.py)', '', 'Joint best fits (background + eBOSS DR16 fσ8); Δ > 0 = better than ΛCDM.', '',
      '| model | joint χ² | Δχ² joint | Δχ² background | Δχ² RSD | ΔAIC (joint) | S8 | DM mass change today |',
      '|---|---|---|---|---|---|---|---|'] + rows + [''] + [f'- {l}' for l in lines]
print('\n'.join(md[4:]))
open(os.path.join(HERE, 'results.md'), 'w').write('\n'.join(md) + '\n')
json.dump(dict(verdict=verdict, criteria=crit, models=out), open(os.path.join(HERE, 'output.json'), 'w'), indent=1, default=float)

# figure: grid maps (Δχ² joint, ΔRSD, S8) and w_eff(z) at the DPT and TQ best fits
lgs = sorted({r['log10_L0'] for r in grid}); v1s = sorted({r['v1'] for r in grid})
L = min((r for r in grid if r['chi2'] is not None and r['v1'] == 0.0), key=lambda r: r['chi2']['total'])['chi2']
def M(key):
    A = np.full((len(lgs), len(v1s)), np.nan)
    for r in grid:
        if r['chi2'] is None:
            continue
        i, j = lgs.index(r['log10_L0']), v1s.index(r['v1'])
        A[i, j] = {'joint': L['total'] - r['chi2']['total'], 'rsd': L['rsd'] - r['chi2']['rsd'], 'S8': r['chi2']['S8']}[key]
    return A
fig, ax = plt.subplots(1, 4, figsize=(20, 4.8))
for a, (key, title, cmap, lims) in zip(ax[:3], (('joint', 'Δχ² (background + fσ8) vs ΛCDM', 'RdBu_r', (-6, 6)),
                                              ('rsd', 'Δχ² from fσ8 alone (positive = better)', 'RdBu_r', (-6, 6)),
                                              ('S8', 'S8 (ΛCDM ≈ 0.81)', 'viridis', (0.75, 1.0)))):
    A = M(key)
    im = a.imshow(np.clip(A, *lims), origin='lower', aspect='auto', cmap=cmap, vmin=lims[0], vmax=lims[1],
                  extent=[-0.5, len(v1s) - 0.5, -0.5, len(lgs) - 0.5])
    for i in range(len(lgs)):
        for j in range(len(v1s)):
            a.text(j, i, 'unphys' if np.isnan(A[i, j]) else (f'{A[i, j]:.3f}' if key == 'S8' else f'{A[i, j]:+.1f}'),
                   ha='center', va='center', fontsize=6.5)
    a.set_xticks(range(len(v1s))); a.set_xticklabels([f'{v:g}' for v in v1s]); a.set_xlabel('tilt v1')
    a.set_yticks(range(len(lgs))); a.set_yticklabels([f'{v:g}' for v in lgs]); a.set_ylabel('log10 Λ0')
    a.set_title(title, fontsize=10); plt.colorbar(im, ax=a)
for k, col in (('dpt', 'C3'), ('tq', 'C1')):
    x = fits[k]['x']
    L0 = 10 ** x['log10_L0'] if k == 'dpt' else 0.0
    m = D.DarkBG(x['omega_b'], x['omega_cdm'], L0, x['v1']); bg = m.solve(x['h'])
    zw, w = D.w_eff(bg, x['omega_b'], x['omega_cdm'])
    ax[3].plot(zw, w, color=col, label=names[k])
z = np.linspace(0, 2.5, 200); a_ = 1 / (1 + z)
xw = fits['w0wa']['x']
ax[3].plot(z, xw['w0'] + xw['wa'] * (1 - a_), 'C2--', label=f"w0waCDM (w0 = {xw['w0']:.2f}, wa = {xw['wa']:.2f})")
ax[3].axhline(-1, color='k', lw=0.8); ax[3].set_xlim(0, 2.5); ax[3].set_ylim(-1.6, -0.4)
ax[3].set_xlabel('z'); ax[3].set_ylabel('w_eff (observer assumes uncoupled dark matter)'); ax[3].legend(fontsize=8)
ax[3].set_title('Apparent dark-energy equation of state at the best fits', fontsize=10)
fig.tight_layout()
os.makedirs(os.path.join(HERE, 'figures'), exist_ok=True)
fig.savefig(os.path.join(HERE, 'figures', 'sim157_dark.png'), dpi=130)
